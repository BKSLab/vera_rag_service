"""Реквизиты нормативного акта и правила их представления.

Наименование документа хранится разобранным на реквизиты, а не одной строкой:
собрать строку из реквизитов можно всегда, разобрать обратно — уже нет.
Официальный портал правовой информации хранит их так же — вид акта и
наименование лежат в разных полях (`docpassing` и `docnames`).
"""

